#!/usr/bin/env node
// Builds docs/LIVE-CHECKS.md: every item across the rounds that's built but not
// yet seen working ([~]), plus Rounds 6–7's open items ([ ]), grouped by round
// and section, each with where it lives. The local session (Mac, phone or
// Simulator) walks it and flips statuses in docs/rounds/*. Re-run after:
//   node tools/hub/live-checks.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../..', import.meta.url));
const DIR = join(ROOT, 'docs/rounds');
const ITEM = /^(\s*)(?:(\d+[a-z]?)\.|-)\s+\[(~| )\]\s+(.*)$/;
const OPEN_TOO = new Set(['round-6.md', 'round-7.md']);

const rounds = readdirSync(DIR)
  .filter((f) => /^round-\d+\.md$/.test(f))
  .sort((a, b) => Number(b.match(/\d+/)[0]) - Number(a.match(/\d+/)[0]));

let total = 0;
const body = [];
for (const file of rounds) {
  const lines = readFileSync(join(DIR, file), 'utf8').split('\n');
  const title = (lines.find((l) => l.startsWith('# ')) ?? file).replace(/^# /, '');
  let section = '';
  const groups = new Map();
  lines.forEach((line, i) => {
    if (/^##\s/.test(line)) section = line.replace(/^##\s+/, '');
    const m = ITEM.exec(line);
    if (!m) return;
    const [, , num, mark, text] = m;
    if (mark === ' ' && !OPEN_TOO.has(file)) return;
    const label = mark === '~' ? 'check' : 'open';
    const entry = `- [ ] ${num ? `**${num}.** ` : ''}${text.trim()} _(${label}, [${file}:${i + 1}](rounds/${file}#L${i + 1}))_`;
    if (!groups.has(section)) groups.set(section, []);
    groups.get(section).push(entry);
    total += 1;
  });
  if (!groups.size) continue;
  const n = [...groups.values()].reduce((s, g) => s + g.length, 0);
  body.push(`## ${file.replace('.md', '').replace('round-', 'Round ')}: ${title} (${n})`, '');
  for (const [sec, items] of groups) {
    if (sec) body.push(`### ${sec}`, '');
    body.push(...items, '');
  }
}

const head = `# Live checks

Everything that's built but not yet **seen working** on the phone or in the
Simulator, from every round, plus Rounds 6 and 7's open items. ${total} items.
Generated by \`node tools/hub/live-checks.mjs\`; don't edit by hand.

## How to walk it (local session)

1. Build the latest main on the phone: \`git pull && npm install && npx expo prebuild -p ios && ./scripts/build-phone.sh\`
   (or \`npx expo run:ios\` for the Simulator).
2. Start with **Do these first** below, then go round by round, newest first.
3. For each item, do what it says and watch for the result. Then in the round file
   (the link after each item):
   - works → change \`[~]\` to \`[x]\` (add "— seen" and anything worth noting)
   - broken → leave \`[~]\`, add "— bug: what happened", and list it under Round 7 G
   - no longer in the app or not worth doing → \`[–]\` with why
4. Re-run \`node tools/hub/live-checks.mjs\` and commit on a branch; open a PR.

Helpers: night clock \`brainnavigator://?night=23:30\` (\`?night=off\` to stop);
show mode (Settings → Show) for sample student Riley; Reduce Motion, largest
text and VoiceOver in iPhone Settings → Accessibility; the phone's date
(Settings → General → Date & Time) for date-bound things like Halloween.

## Do these first (Waves 9–11, newest build)

- [ ] Canvas still syncs after the update (token moved to the keychain) — Connections → Canvas
- [ ] Shake the phone firmly on the Desk: "Drop a worry" opens; save one → Undo bar; it's in the Worry box
- [ ] Walking around with the phone opens nothing; Settings → Privacy → Shake to drop a worry off → shaking does nothing
- [ ] Shake on Wins: Ember reads out a past win; no worry sheet
- [ ] Mark a homework done → "Done, not turned in yet" and a Mark turned in chip → "Done and turned in"
- [ ] Phone date Oct 31: Ember wears a pumpkin hat and says hello once
- [ ] VoiceOver: Your day → Plan a block, swatches read "Gold block"…; a filled text field still says what it's for
- [ ] Ember replies in chat (confirms the Supabase project, Round 7 G21)
- [ ] The app opens on iOS 27 (scene life cycle) and deep links land (\`brainnavigator://about\`)

`;
writeFileSync(join(ROOT, 'docs/LIVE-CHECKS.md'), head + body.join('\n'));
console.log(`docs/LIVE-CHECKS.md: ${total} items`);
